<?php

namespace Nitro\Fusion\Tests\Feature;

use Illuminate\Testing\TestResponse;
use Nitro\Fusion\Compiler\CompileException;
use Nitro\Fusion\Testing\AssertableFusion;
use Nitro\Fusion\Tests\TestCase;
use Nitro\Fusion\ViewPages;
use PHPUnit\Framework\Attributes\DataProvider;

/**
 * Pages that are only a view (@page(...)), returned by a controller as Inertia's pages are, their
 * actions the controller's routes (the fixture's NotesController and fusion/pages/notes.blade.php).
 */
class ViewPagesTest extends TestCase
{
    private function page(string $method, string $uri, array $data = [], array $headers = []): TestResponse
    {
        $server = [];
        foreach ($headers as $name => $value) {
            $server['HTTP_'.strtoupper(str_replace('-', '_', $name))] = $value;
        }

        return TestResponse::fromBaseResponse($this->request($method, $uri, $server, $data === [] ? null : json_encode($data)));
    }

    #[DataProvider('frameworks')]
    public function test_a_view_with_page_is_a_page_with_a_class_made_from_it(string $framework): void
    {
        $this->boot($framework);

        $class = $this->fusion()->registry()->class('pages::notes');
        $this->assertSame(ViewPages::NAMESPACE.'\\Notes', $class);

        $meta = $this->fusion()->meta('pages::notes');
        $this->assertTrue($meta->page);
        $this->assertSame('Notes', $meta->title);
        $this->assertTrue($meta->properties['notes']->locked, 'props come from the controller: read-only in the browser');
        $this->assertTrue($meta->properties['count']->locked);
        $this->assertFalse($meta->properties['open']->locked, 'state is the page\'s own');
        $this->assertTrue($meta->properties['form']->remember);
        $this->assertNotNull($meta->properties['filter']->url);
        $this->assertSame(['title' => ''], $meta->properties['form']->default);

        /** What the class is made of (made again here: fusion:clear empties the compiled directory). */
        $source = $this->app->make(ViewPages::class)->generate('pages::notes', $this->app->make('view')->getFinder()->find('fusion.pages.notes'));
        $this->assertStringContainsString('Generated by Fusion', $source);
        $this->assertStringContainsString("public mixed \$form = ['title' => ''];", $source);
    }

    #[DataProvider('frameworks')]
    public function test_a_controller_renders_it_by_its_view_name(string $framework): void
    {
        $this->boot($framework);

        $response = $this->page('GET', '/notes')->assertOk();
        $this->assertStringContainsString('class="notes"', (string) $response->getContent());
        $this->assertStringNotContainsString('@page', (string) $response->getContent(), '@page renders nothing');

        $response->assertFusion(fn (AssertableFusion $page) => $page
            ->page('pages::notes')
            ->where('notes', [])
            ->where('count', 0)
            ->where('open', false));

        /** A fusion:navigate visit gets the page's data, as any page's. */
        $this->page('GET', '/notes', headers: ['Accept' => 'application/json', 'X-Fusion-Navigate' => '1'])
            ->assertOk()
            ->assertJsonPath('fusion', 1);
    }

    /** A $put, $patch or $delete redirected back is a 303: the browser follows it with a GET. */
    #[DataProvider('frameworks')]
    public function test_its_actions_redirect_back_with_a_303(string $framework): void
    {
        $this->boot($framework);
        $headers = ['Accept' => 'application/json', 'X-Fusion-Navigate' => '1', 'Content-Type' => 'application/json'];

        $this->page('GET', '/notes');
        $this->app->make('session')->put('notes', ['One', 'Two']);

        $this->assertSame(303, $this->page('DELETE', '/notes/0', headers: $headers)->getStatusCode());
        $this->assertSame(302, $this->page('DELETE', '/notes/0', headers: ['Accept' => 'application/json'])->getStatusCode(), 'not a Fusion request: as it was');
    }

    public function test_page_is_read_and_checked(): void
    {
        $declared = ViewPages::declaration("@page(title: 'T', props: ['a', 'b' => [1]], state: ['c' => ['x' => '']], remember: ['c'])\n<div></div>");

        $this->assertSame('T', $declared['title']);
        $this->assertSame(['a' => null, 'b' => [1]], $declared['props']);
        $this->assertSame(['c' => ['x' => '']], $declared['state']);
        $this->assertSame(['c'], $declared['remember']);
        $this->assertNull(ViewPages::declaration('<div>@@page(not one)</div>'), 'escaped');

        foreach ([
            "@page(props: ['a'], state: ['a' => 1])" => 'both a prop and state',
            "@page(remember: ['nope'])" => "remember: names state",
            "@page(props: ['a'], extra: 1)" => 'named arguments',
            '@page(state: [\'a\' => now()])' => 'written out',
            "@page(props: ['a b'])" => 'not a property name',
        ] as $source => $message) {
            try {
                ViewPages::declaration($source);
                $this->fail("{$source} must not be accepted");
            } catch (CompileException $e) {
                $this->assertStringContainsString($message, $e->getMessage(), $source);
            }
        }
    }

    /** fusion:page-class: the view page grown into a page class, typed, with its attributes; @page leaves the view. */
    public function test_a_view_page_grows_into_a_page_class(): void
    {
        $view = "{{-- notes --}}\n@page(\n    title: 'Notes',\n    props: ['notes' => [], 'count' => 0, 'latest'],\n    state: ['form' => ['title' => ''], 'filter' => '', 'open' => false],\n    remember: ['form'],\n    url: ['filter'],\n)\n<div class=\"notes\">{{ \$count }}</div>\n";

        $php = ViewPages::pageClass($view, 'App\\Fusion\\Pages', 'Notes');

        foreach ([
            'namespace App\\Fusion\\Pages;',
            'use Nitro\\Fusion\\Attributes\\Locked;',
            "#[Title('Notes')]",
            'class Notes extends Component',
            "#[Locked]\n    public array \$notes = [];",
            "#[Locked]\n    public int \$count = 0;",
            "#[Locked]\n    public mixed \$latest = null;",
            "#[Remember]\n    public array \$form = ['title' => ''];",
            "#[Url]\n    public string \$filter = '';",
            'public bool $open = false;',
        ] as $expected) {
            $this->assertStringContainsString($expected, $php);
        }

        (new \PhpParser\ParserFactory)->createForHostVersion()->parse($php);

        $this->assertSame("{{-- notes --}}\n<div class=\"notes\">{{ \$count }}</div>\n", ViewPages::withoutDeclaration($view));
    }

    /** A page class of a view page's name takes its place (a page grown with fusion:page-class). */
    public function test_a_page_class_wins_over_a_view_page_of_its_name(): void
    {
        $registry = new \Nitro\Fusion\Registry(
            ['namespace' => 'Nitro\\Fusion\\Tests\\Fixtures\\Components', 'path' => dirname(__DIR__).'/Fixtures/Components', 'views' => 'fusion.components'],
            ['namespace' => 'Nitro\\Fusion\\Tests\\Fixtures\\Pages', 'path' => dirname(__DIR__).'/Fixtures/Pages', 'views' => 'fusion.pages'],
            viewPages: fn () => ['pages::counter' => ViewPages::NAMESPACE.'\\Counter', 'pages::only-a-view' => ViewPages::NAMESPACE.'\\OnlyAView'],
        );

        $this->assertSame(\Nitro\Fusion\Tests\Fixtures\Pages\Counter::class, $registry->class('pages::counter'));
        $this->assertSame(ViewPages::NAMESPACE.'\\OnlyAView', $registry->class('pages::only-a-view'));
    }

    public function test_class_names_and_page_names_round_trip(): void
    {
        $this->assertSame(ViewPages::NAMESPACE.'\\FeePlans_Index', ViewPages::className('pages::fee-plans.index'));
        $this->assertSame('pages::fee-plans.index', ViewPages::pageName(ViewPages::NAMESPACE.'\\FeePlans_Index'));
        $this->assertNull(ViewPages::pageName('App\\Fusion\\Pages\\Index'));
    }
}
