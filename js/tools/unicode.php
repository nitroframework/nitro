<?php

/**
 * Writes the Unicode data of js/functions, read from this PHP (run it again when PHP's mbstring
 * or voku/portable-ascii changes their Unicode version):
 *
 *   _mb_wide.js     the code points mb_strwidth() counts as 2, as [first, last] ranges
 *   _mb_title.js    the characters whose MB_CASE_TITLE is not their upper case
 *   _str_ascii.js   Str::ascii()'s transliteration (language "en") of the characters it keeps
 *
 *   php js/tools/unicode.php
 */
require __DIR__.'/../../vendor/autoload.php';

use Illuminate\Support\Str;

$flags = JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR;
$wide = [];
$title = [];
$ascii = [];
$start = null;

for ($c = 0; $c <= 0x110000; $c++) {
    $surrogate = $c >= 0xD800 && $c <= 0xDFFF;
    $valid = $c <= 0x10FFFF && ! $surrogate;
    $char = $valid ? mb_chr($c, 'UTF-8') : '';
    $isWide = $valid && mb_strwidth($char, 'UTF-8') === 2;

    if ($isWide && $start === null) {
        $start = $c;
    } elseif (! $isWide && $start !== null && ! $surrogate) {
        $wide[] = [$start, $c - 1];
        $start = null;
    }

    if (! $valid) {
        continue;
    }

    if ($c >= 0x80 && mb_convert_case($char, MB_CASE_TITLE, 'UTF-8') !== mb_strtoupper($char, 'UTF-8')) {
        $title[$char] = mb_convert_case($char, MB_CASE_TITLE, 'UTF-8');
    }

    $transliterated = Str::ascii($char);

    if ($c < 0x80 ? $transliterated !== $char : $transliterated !== '') {
        $ascii[$char] = $transliterated;
    }
}

/** Str::ascii() works character by character: the table is all of it (checked on a sample). */
$sample = 'Ærøskøbing, Straße, ﬁ, Ωμέγα, Привет, 日本語, 😀, ǅ, İstanbul, Łódź, “quotes” — dash';
$byTable = implode('', array_map(fn (string $char) => $ascii[$char] ?? (strlen($char) === 1 ? $char : ''), mb_str_split($sample)));

if ($byTable !== Str::ascii($sample)) {
    throw new RuntimeException("Str::ascii() is not character by character: [{$byTable}] and [".Str::ascii($sample).']');
}

$header = fn (string $what) => "// Generated by js/tools/unicode.php from PHP ".PHP_VERSION.": {$what}. Do not edit.\n";

file_put_contents(__DIR__.'/../functions/_mb_wide.js', $header('mb_strwidth()\'s code points of width 2, as [first, last] ranges')
    .'function _mb_wide() {'."\n    return ".json_encode($wide, $flags).";\n}\n");
file_put_contents(__DIR__.'/../functions/_mb_title.js', $header('the characters whose title case (MB_CASE_TITLE) is not their upper case')
    .'function _mb_title() {'."\n    return ".json_encode((object) $title, $flags).";\n}\n");
file_put_contents(__DIR__.'/../functions/_str_ascii.js', $header('Str::ascii() (language "en"): the characters it does not keep as they are, and what it makes of them (the other non-ASCII ones it drops)')
    .'function _str_ascii() {'."\n    return ".json_encode((object) $ascii, $flags).";\n}\n");

printf("%d wide ranges, %d title exceptions, %d transliterations\n", count($wide), count($title), count($ascii));
